"""Validate data/tools.yaml and render README.md from it.

    python scripts/build_readme.py                 # validate + write README.md
    python scripts/build_readme.py --check         # fail if README.md is out of date
    python scripts/build_readme.py --pr-body out.md   # review checklist for the weekly PR
"""
from __future__ import annotations

import argparse
import datetime as dt
import re
import sys

from common import ROOT, STATUSES, load_config, load_tools

README = ROOT / "README.md"
REPO = "amnahsiddiqa/imaging-spatial-tx-tools"


def anchor(title: str) -> str:
    return re.sub(r"[^\w\- ]", "", title.lower()).replace(" ", "-")


def cell(text, limit: int = 220) -> str:
    text = re.sub(r"\s+", " ", str(text or "")).strip().replace("|", "\\|")
    return text if len(text) <= limit else text[: limit - 1].rstrip() + "…"


def paper_link(p: dict | None) -> str:
    if not p:
        return ""
    label = "Preprint" if p.get("preprint") else "Paper"
    year = f" {p['year']}" if p.get("year") else ""
    return f"[{label}{year}](https://doi.org/{p['doi']})"


def validate(tools: list[dict], cfg: dict) -> list[str]:
    cats = {c["id"] for c in cfg["categories"]} | {"uncategorised"}
    errors, seen = [], set()
    for i, t in enumerate(tools):
        where = f"entry {i + 1} ({t.get('id', '?')})"
        for f in ("id", "name", "url", "status"):
            if not t.get(f):
                errors.append(f"{where}: missing '{f}'")
        if t.get("status") not in STATUSES:
            errors.append(f"{where}: status must be one of {STATUSES}, got {t.get('status')!r}")
        if t.get("status") != "rejected" and t.get("category") not in cats:
            errors.append(f"{where}: unknown category {t.get('category')!r}")
        if t.get("status") == "listed" and t.get("category") == "uncategorised":
            errors.append(f"{where}: listed tools need a real category")
        if t.get("id") in seen:
            errors.append(f"{where}: duplicate id")
        seen.add(t.get("id"))
    return errors


def name_cell(t: dict, stale_before: str) -> str:
    flags = ""
    if t.get("archived"):
        flags += " 🗄️"
    elif t.get("last_push") and t["last_push"] < stale_before:
        flags += " 💤"
    return f"[{cell(t['name'], 60)}]({t['url']}){flags}"


def render(tools: list[dict], cfg: dict) -> str:
    listed = [t for t in tools if t["status"] == "listed"]
    pending = [t for t in tools if t["status"] == "candidate"]
    stale_before = (dt.date.today() - dt.timedelta(days=730)).isoformat()
    groups = {c["id"]: [] for c in cfg["categories"]}
    for t in listed:
        groups[t["category"]].append(t)
    updated = max([t.get("added", "") for t in tools] + [""])

    out = [
        "<!-- Generated by scripts/build_readme.py from data/tools.yaml. Edit the YAML, not this file. -->",
        "# Imaging-based In Situ Spatial Transcriptomics Tools",
        "",
        "A curated, automatically updated list of software for **imaging-based (in situ) spatial "
        "transcriptomics**: 10x Genomics Xenium, Bruker/NanoString CosMx, Vizgen MERSCOPE and MERFISH, "
        "seqFISH, STARmap, in situ sequencing (ISS), Resolve Molecular Cartography and smFISH-based methods. "
        "Tools are grouped by analysis step. Sequencing-based methods (Visium, Stereo-seq, Slide-seq) are out "
        "of scope unless a tool also handles imaging-based data.",
        "",
        f"![tools](https://img.shields.io/badge/tools-{len(listed)}-2b7bb9) "
        f"![awaiting review](https://img.shields.io/badge/awaiting%20review-{len(pending)}-e0a100) "
        f"[![weekly discovery](https://github.com/{REPO}/actions/workflows/weekly-discovery.yml/badge.svg)]"
        f"(https://github.com/{REPO}/actions/workflows/weekly-discovery.yml)",
        "",
        "Every Monday a GitHub Action searches GitHub and Europe PMC (PubMed + bioRxiv/medRxiv) for new tools "
        "and opens a pull request with the hits for review ([how it works](#how-this-list-is-maintained)).",
        "",
        "**Related lists:** [Spatial_transcriptomics_tools](https://github.com/p-gueguen/Spatial_transcriptomics_tools) "
        "(all spatial technologies; this list's model) · "
        "[awesome_spatial_omics](https://github.com/crazyhottommy/awesome_spatial_omics)",
        "",
        "**Legend:** Platforms = imaging technologies named in the repo README or paper abstract (detected automatically; blank = none named) · "
        "★ = GitHub stars · 🗄️ archived by its owner · 💤 no commits for 2+ years",
        "",
        "## Contents",
        "",
    ]
    for c in cfg["categories"]:
        if groups[c["id"]]:
            out.append(f"- [{c['title']}](#{anchor(c['title'])}) ({len(groups[c['id']])})")
    if pending:
        out.append(f"- [Awaiting review](#awaiting-review) ({len(pending)})")
    out.append("- [How this list is maintained](#how-this-list-is-maintained)")

    for c in cfg["categories"]:
        rows = sorted(groups[c["id"]], key=lambda t: t["name"].lower())
        if not rows:
            continue
        out += ["", f"## {c['title']}", "",
                "| Tool | Language | Platforms | Description | Paper | ★ |",
                "|---|---|---|---|---|--:|"]
        for t in rows:
            out.append(f"| {name_cell(t, stale_before)} | {cell(t.get('language'), 20)} | "
                       f"{', '.join(t.get('platforms') or [])} | {cell(t.get('description'))} | "
                       f"{paper_link(t.get('paper'))} | {t.get('stars', '') if t['id'].startswith('github:') else ''} |")

    if pending:
        titles = {c["id"]: c["title"] for c in cfg["categories"]} | {"uncategorised": "Uncategorised"}
        out += ["", "## Awaiting review", "",
                "Found by the weekly search and not yet checked. Treat these as leads, not recommendations.", "",
                "| Tool | Suggested category | Platforms | Description | Paper | Found |",
                "|---|---|---|---|---|---|"]
        for t in sorted(pending, key=lambda t: (t.get("added", ""), t["name"].lower()), reverse=True):
            note = f" *({cell(t['note'], 80)})*" if t.get("note") else ""
            out.append(f"| {name_cell(t, stale_before)} | {titles.get(t['category'], t['category'])} | "
                       f"{', '.join(t.get('platforms') or [])} | {cell(t.get('description'))}{note} | "
                       f"{paper_link(t.get('paper'))} | {t.get('added', '')} |")

    out += ["", "## How this list is maintained", "",
            "- **Source of truth:** [`data/tools.yaml`](data/tools.yaml). This README is generated from it by "
            "[`scripts/build_readme.py`](scripts/build_readme.py); edits made here directly are overwritten.",
            "- **Weekly discovery** ([`scripts/discover.py`](scripts/discover.py), run by "
            "[`weekly-discovery.yml`](.github/workflows/weekly-discovery.yml)):",
            "  - Europe PMC: papers and preprints from the last 21 days whose abstract mentions an imaging-based "
            "platform and whose title or abstract reads as a method, tool, benchmark or resource. Code links are "
            "taken from the abstract, or from a GitHub repo named after the tool. This is how brand-new tools "
            "are usually found.",
            "  - GitHub: repositories with at least 10 stars that mention an imaging-based platform (Xenium, "
            "CosMx, MERFISH, seqFISH, STARmap, ISS, …) in their name, description, topics or README and are "
            "not in the list yet. Each is scored on simple tool-likeness signals (install instructions, licence, "
            "description, stars, linked paper; minus points for one-off analysis repos) and kept above a fixed "
            "score. New 0-star repos are skipped on purpose: almost all are personal analyses.",
            "  - Hits are sorted into categories by keyword rules in [`config/search.yaml`](config/search.yaml) "
            "and added with `status: candidate`. Stars, last commit and archived status of listed tools are "
            "refreshed in the same run.",
            "  - If anything changed, the Action opens (or adds to) one pull request, `auto/weekly-candidates`, "
            "for a human to review. Nothing reaches the main list without that review.",
            "- **Papers** linked from a repo are the first DOI in its README that resolves in Crossref or DataCite; "
            "preprints are labelled *Preprint*.",
            "- **Limits:** keyword search misses tools that never name a platform, classification is approximate, "
            "and the paper link can occasionally be a related paper rather than the tool's own. Corrections "
            "are welcome via [CONTRIBUTING.md](CONTRIBUTING.md).",
            "", f"*Last list change: {updated}.*", ""]
    return "\n".join(out)


def pr_body(tools: list[dict], cfg: dict) -> str:
    pending = [t for t in tools if t["status"] == "candidate"]
    titles = {c["id"]: c["title"] for c in cfg["categories"]} | {"uncategorised": "Uncategorised"}
    lines = ["Weekly discovery found new imaging-based spatial transcriptomics tools.", "",
             "### How to review", "",
             "Edit `data/tools.yaml` on this branch (the pencil icon in *Files changed* works). For each "
             "`status: candidate` entry, either:",
             "- set `status: listed` and fix `category`, `description` or `platforms` if needed, or",
             "- set `status: rejected` (optionally add a `note:` saying why); it will not be proposed again.",
             "",
             "The README re-renders on every push. Candidates you leave alone stay under *Awaiting review* "
             "after merge. Next week's run adds to this PR while it is open.", "",
             f"### Candidates ({len(pending)})", "",
             "| Tool | Suggested category | Score | Source | Paper | Note |", "|---|---|--:|---|---|---|"]
    for t in sorted(pending, key=lambda t: (t.get("category", ""), t["name"].lower())):
        lines.append(f"| [{cell(t['name'], 50)}]({t['url']}) — {cell(t.get('description'), 120)} | "
                     f"{titles.get(t['category'], t['category'])} | {t.get('score', '')} | {t.get('source', '')} | "
                     f"{paper_link(t.get('paper'))} | {cell(t.get('note'), 80)} |")
    lines += ["", f"_Opened by the [weekly-discovery](https://github.com/{REPO}/actions/workflows/weekly-discovery.yml) workflow._"]
    return "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--pr-body")
    args = ap.parse_args()

    cfg, tools = load_config(), load_tools()
    errors = validate(tools, cfg)
    if errors:
        print("data/tools.yaml has problems:\n  " + "\n  ".join(errors), file=sys.stderr)
        sys.exit(1)
    if args.pr_body:
        with open(args.pr_body, "w") as fh:
            fh.write(pr_body(tools, cfg))
        return
    text = render(tools, cfg)
    if args.check:
        if not README.exists() or README.read_text() != text:
            sys.exit("README.md is out of date: run python scripts/build_readme.py")
        return
    README.write_text(text)
    print(f"README.md written: {sum(t['status'] == 'listed' for t in tools)} listed, "
          f"{sum(t['status'] == 'candidate' for t in tools)} awaiting review")


if __name__ == "__main__":
    main()
